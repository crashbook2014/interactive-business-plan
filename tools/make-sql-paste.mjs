/* Build tools/apply-all.sql — every migration, in order, as one paste.
 *
 *   node tools/make-sql-paste.mjs
 *
 * WHY THIS EXISTS. `supabase db push` needs the CLI, a linked project and the
 * database password. Not everyone has all three in front of them, and the
 * Supabase dashboard's SQL Editor needs none of them. This turns five files
 * into one paste.
 *
 * WHY IT IS GENERATED RATHER THAN MAINTAINED. A hand-kept copy of five
 * migrations is a copy that goes stale the first time one of them changes, and
 * nothing would say so. ask.test.js asserts the committed file matches what
 * this produces today, exactly as it does for the corpus.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "supabase/migrations");

/* `since` exists because apply-all.sql is not re-runnable: 0001 creates its
   tables without IF NOT EXISTS, so pasting the whole file into a project that
   already has them fails (harmlessly — the BEGIN/COMMIT rolls it back — but it
   fails). A project mid-way through needs exactly the migrations it lacks, and
   working that out by hand at the moment you are trying to fix something is
   how the wrong half gets pasted. Pass the last version already applied. */
export function buildPaste(since) {
  let files = readdirSync(DIR).filter((f) => f.endsWith(".sql")).sort();
  if (since) {
    const after = String(since).padStart(4, "0");
    files = files.filter((f) => f.split("_")[0] > after);
    if (!files.length) throw new Error(`nothing after ${after} — the project is up to date`);
  }
  const rows = files.map((f) => {
    const version = f.split("_")[0];
    const name = f.replace(/^\d+_/, "").replace(/\.sql$/, "");
    return { file: f, version, name };
  });

  const head = `-- ============================================================================
-- Wodouh — ${since ? `migrations after ${since}` : `all ${files.length} migrations`}, in order, as one paste.
--
-- GENERATED by tools/make-sql-paste.mjs from supabase/migrations/.
-- Do not edit this file; edit a migration and regenerate.
--
-- FOR THE SUPABASE SQL EDITOR. Use this when you cannot run
-- \`supabase db push\` — no CLI, no database password, no terminal.
-- Dashboard -> SQL Editor -> paste -> Run.
--
-- IT RECORDS ITSELF. The block at the end writes the versions into
-- supabase_migrations.schema_migrations, the table the CLI reads to decide
-- what still needs applying. Without it, a later \`supabase db push\` would see
-- unapplied migrations and try to run them all again against a schema that
-- already has the tables. With it, the CLI and the dashboard agree.
--
-- RUN IT ONCE. It is NOT idempotent: 0001 creates tables without IF NOT
-- EXISTS, so a second run stops at \`relation "profiles" already exists\`.
-- Verified by running it twice rather than assuming.
--
-- A SECOND RUN IS HARMLESS ANYWAY, which is why the whole thing is wrapped in
-- BEGIN/COMMIT. The error aborts the transaction, COMMIT never happens, and
-- nothing from that run is applied. An error message and an unchanged
-- database, not a half-applied one.
--
-- IT DOES MAKE YOU AN OPERATOR, if your address is in public.admin_allowlist
-- (0008). The trigger there promotes an allowlisted, CONFIRMED email on first
-- sign-in, and also promotes anyone already signed in — so this is correct
-- whichever order those happen in.
-- ============================================================================

begin;
`;

  const body = rows.map(({ file }) =>
    `\n-- ===================================================================\n` +
    `-- ${file}\n` +
    `-- ===================================================================\n` +
    readFileSync(path.join(DIR, file), "utf8")
  ).join("");

  const values = rows.map((r) => `  ('${r.version}', '${r.name}')`).join(",\n");

  const tail = `
-- ============================================================================
-- Bookkeeping: tell the CLI these are applied, so it never re-runs them.
-- ============================================================================
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (
  version text primary key,
  statements text[],
  name text
);
insert into supabase_migrations.schema_migrations (version, name) values
${values}
on conflict (version) do nothing;

commit;

-- ============================================================================
-- BECOMING AN OPERATOR — nothing to do here any more.
--
-- public.admins still has NO client write policy: nothing reachable from a
-- browser can grant console access, including the console itself. What changed
-- is WHERE the grant comes from. 0008 adds public.admin_allowlist, keyed by
-- email, and a trigger on auth.users that promotes a matching CONFIRMED
-- address on first sign-in. It also promotes anyone already signed in, so it
-- is correct whichever order those two things happen in.
--
-- This block used to say "after you have signed into the app once, and not
-- before" and hand you an INSERT to uncomment. That was the chicken-and-egg
-- itself written down as a procedure: admins.user_id references auth.users,
-- the console is what you sign in to, and until you were an operator it showed
-- you nothing.
--
-- To add or remove an operator, edit public.admin_allowlist. It is RLS-on with
-- no policies, so only this editor and the service role can see or change it.
-- ============================================================================

-- Who is on the list, and who has actually been promoted:
-- select a.email, a.role, (u.id is not null) as signed_in_yet
--   from public.admin_allowlist a
--   left join auth.users u on lower(btrim(u.email)) = a.email;
`;

  return head + body + tail;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const arg = (name) => {
    const hit = process.argv.slice(2).find((a) => a.startsWith(`--${name}=`));
    return hit ? hit.slice(name.length + 3) : null;
  };
  const since = arg("since");
  /* A partial paste is deliberately NOT written to tools/apply-all.sql: that
     file is committed and asserted against the full set, and a file whose
     contents depend on what some project happens to have applied would go
     stale the moment it did. */
  const out = arg("out") || (since ? null : path.join(ROOT, "tools/apply-all.sql"));
  if (!out) { console.error("--since needs --out=<path>; apply-all.sql is the full set only"); process.exit(1); }
  writeFileSync(out, buildPaste(since));
  console.log(`wrote ${out}${since ? ` — everything after ${since}` : ""}`);
}
